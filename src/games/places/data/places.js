export const PLACES = [...NEWCOMER, ...EXPLORER, ...RESIDENT, ...CITIZEN, ...AMBASSADOR]

/**
 * getSubLevelPlaces — return the 5 places for a given level + sub-level.
 *
 * @param {string} levelId  — 'newcomer' | 'explorer' | …
 * @param {number} subLevel — 1–5
 * @param {Array}  pool     — default PLACES; may be server-overridden
 * @returns {Array} 5-element slice
 */
export function getSubLevelPlaces(levelId, subLevel, pool = PLACES) {
  const levelPlaces = pool.filter(p => p.level === levelId)
  const start = (subLevel - 1) * 5
  return levelPlaces.slice(start, start + 5)
}
